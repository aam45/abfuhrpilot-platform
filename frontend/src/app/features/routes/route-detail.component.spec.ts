import { TestBed } from '@angular/core/testing';
import { HttpTestingController, provideHttpClientTesting } from '@angular/common/http/testing';
import { provideHttpClient } from '@angular/common/http';
import { ActivatedRoute, provideRouter, convertToParamMap } from '@angular/router';
import { RouteDetailComponent } from './route-detail.component';
import { API_BASE } from '../../core/config';

const ROUTE_ID = 'r1';

function routeDto(status = 'Planned') {
  return {
    id: ROUTE_ID, routeNumber: 'R-001', name: 'Tour', date: '2026-07-03', wasteTypeId: 'w1', wasteTypeName: 'Hausmüll',
    vehicleId: null, vehicleName: null, driverId: null, driverName: null, startDepotId: null, endDestinationId: null,
    status, plannedStartTime: null, plannedEndTime: null, actualStartTime: null, actualEndTime: null,
    stopCount: 2, doneCount: 0, problemCount: 0,
  };
}
// Stops WITHOUT coordinates → the map shows its empty state (no Leaflet init) — keeps the test light.
const stops = [
  { id: 's1', routeId: ROUTE_ID, sequenceNumber: 1, address: 'Hauptstr 1', latitude: null, longitude: null, wasteTypeId: 'w1', pickupType: 'RegularBinPickup', status: 'Open' },
  { id: 's2', routeId: ROUTE_ID, sequenceNumber: 2, address: 'Marktplatz 3', latitude: null, longitude: null, wasteTypeId: 'w1', pickupType: 'RegularBinPickup', status: 'Open' },
];
const emptyPage = { items: [], page: 1, pageSize: 200, totalCount: 0, totalPages: 0 };
const navLinks = { googleMaps: 'https://www.google.com/maps/dir/?api=1&destination=1,2', appleMaps: 'https://maps.apple.com/?daddr=1,2', openStreetMap: 'https://www.openstreetmap.org/directions' };

describe('RouteDetailComponent — routing UI', () => {
  let http: HttpTestingController;

  function mount(role: 'Dispatcher' | 'Viewer', status = 'Planned') {
    localStorage.setItem('ap_token', 'tok');
    localStorage.setItem('ap_user', JSON.stringify({ id: 'u1', fullName: 'X', email: 'x@y.de', role, companyId: 'c1', isActive: true }));
    TestBed.configureTestingModule({
      imports: [RouteDetailComponent],
      providers: [
        provideHttpClient(), provideHttpClientTesting(), provideRouter([]),
        { provide: ActivatedRoute, useValue: { snapshot: { paramMap: convertToParamMap({ id: ROUTE_ID }) } } },
      ],
    });
    http = TestBed.inject(HttpTestingController);
    const fixture = TestBed.createComponent(RouteDetailComponent);
    fixture.detectChanges(); // ngOnInit → initial loads

    http.expectOne(r => r.url === `${API_BASE}/waste-types`).flush(emptyPage);
    http.expectOne(r => r.url === `${API_BASE}/destinations`).flush(emptyPage);
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}`).flush(routeDto(status));
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/stops`).flush(stops);
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/navigation-links`).flush(navLinks);
    fixture.detectChanges();
    return fixture;
  }

  beforeEach(() => localStorage.clear());
  afterEach(() => http.verify());

  function text(fixture: any) { return (fixture.nativeElement as HTMLElement).textContent ?? ''; }

  it('shows the local-fallback provider state after calculate', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.calculate();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/calculate`).flush({
      provider: 'LocalFallback', providerConfigured: false, warning: 'Routing provider not configured',
      totalDistanceMeters: 1040, totalDurationSeconds: 120, legs: [], geometry: null, excludedStopIds: [],
    });
    fixture.detectChanges();
    expect(text(fixture)).toContain('Lokaler Fallback aktiv');
  });

  it('displays a navigation link (generated by the backend)', () => {
    const fixture = mount('Dispatcher');
    const anchor = (fixture.nativeElement as HTMLElement).querySelector('a[href*="google.com/maps"]');
    expect(anchor).toBeTruthy();
  });

  it('shows an optimized-order preview before applying', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.optimize();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/optimize`).flush({
      provider: 'LocalFallback', providerConfigured: false, warning: null,
      order: [{ stopId: 's2', newSequenceNumber: 1 }, { stopId: 's1', newSequenceNumber: 2 }],
      totalDistanceMeters: 900, totalDurationSeconds: 100, excludedStopIds: [], geometry: null,
    });
    fixture.detectChanges();
    expect(fixture.componentInstance.previewStops().length).toBe(2);
    expect(text(fixture)).toContain('Vorschau optimierte Reihenfolge');
  });

  it('warns when some stops have no coordinates', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.calculate();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/calculate`).flush({
      provider: 'LocalFallback', providerConfigured: false, warning: 'Routing provider not configured',
      totalDistanceMeters: 0, totalDurationSeconds: 0, legs: [], geometry: null, excludedStopIds: ['s1', 's2'],
    });
    fixture.detectChanges();
    expect(fixture.componentInstance.excludedCount()).toBe(2);
    expect(text(fixture)).toContain('ohne Koordinaten');
  });

  it('selecting a stop in the list marks it selected (map-sync state)', () => {
    const fixture = mount('Dispatcher');
    const li: HTMLElement = (fixture.nativeElement as HTMLElement).querySelector('.stops li')!;
    li.click();
    fixture.detectChanges();
    expect(li.classList.contains('selected')).toBeTrue();
    expect(li.getAttribute('aria-selected')).toBe('true');
    li.click(); // toggles off
    fixture.detectChanges();
    expect(li.classList.contains('selected')).toBeFalse();
  });

  it('hides the optimize button for non-editor roles (Viewer)', () => {
    const fixture = mount('Viewer');
    expect(text(fixture)).not.toContain('Route optimieren');
    expect(text(fixture)).toContain('Route berechnen'); // calculate still available
  });

  // ---- truck-aware routing ----

  it('shows an honest truck warning when restrictions were not enforced', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.calculate();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/calculate`).flush({
      provider: 'GraphHopper', providerConfigured: true, warning: null,
      totalDistanceMeters: 5000, totalDurationSeconds: 900, legs: [], geometry: null, excludedStopIds: [],
      routingProfileUsed: 'car', truckRestrictionsApplied: false,
      warnings: [
        { code: 'PROVIDER_USING_CAR_FALLBACK', message: 'car profile', severity: 'Warning' },
        { code: 'TRUCK_RESTRICTIONS_NOT_ENFORCED', message: 'not enforced', severity: 'Warning' },
      ],
    });
    fixture.detectChanges();
    expect(text(fixture)).toContain('Achtung: Diese Route wurde nicht mit LKW-Beschränkungen berechnet.');
    expect(text(fixture)).toContain('Routing-Profil');
    expect(text(fixture)).toContain('nicht aktiv');
  });

  it('shows German missing-height/weight warnings', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.calculate();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/calculate`).flush({
      provider: 'LocalFallback', providerConfigured: false, warning: 'Routing provider not configured',
      totalDistanceMeters: 1000, totalDurationSeconds: 120, legs: [], geometry: null, excludedStopIds: [],
      routingProfileUsed: 'straight-line', truckRestrictionsApplied: false,
      warnings: [
        { code: 'MISSING_VEHICLE_HEIGHT', message: 'Vehicle height missing', severity: 'Warning' },
        { code: 'MISSING_VEHICLE_WEIGHT', message: 'Vehicle weight missing', severity: 'Warning' },
      ],
    });
    fixture.detectChanges();
    expect(text(fixture)).toContain('Fahrzeughöhe fehlt');
    expect(text(fixture)).toContain('Fahrzeuggewicht fehlt');
  });

  it('shows the local-fallback no-truck-rules warning', () => {
    const fixture = mount('Dispatcher');
    fixture.componentInstance.calculate();
    http.expectOne(`${API_BASE}/routes/${ROUTE_ID}/calculate`).flush({
      provider: 'LocalFallback', providerConfigured: false, warning: 'Routing provider not configured',
      totalDistanceMeters: 1000, totalDurationSeconds: 120, legs: [], geometry: null, excludedStopIds: [],
      routingProfileUsed: 'straight-line', truckRestrictionsApplied: false,
      warnings: [
        { code: 'PROVIDER_USING_LOCAL_FALLBACK', message: 'local', severity: 'Info' },
        { code: 'TRUCK_RESTRICTIONS_NOT_ENFORCED', message: 'not enforced', severity: 'Warning' },
      ],
    });
    fixture.detectChanges();
    expect(text(fixture)).toContain('Lokaler Fallback — keine LKW-Regeln');
    expect(text(fixture)).toContain('LKW-Beschränkungen nicht aktiv');
  });
});
